"""Local KeyProvider: a key-encryption key (KEK) file for development and single-VM installs.

File format (JSON, generated by ``secrets-init``, never committed)::

    {"format": "skyline-local-kek", "version": 1, "active": "<key_id>",
     "keys": {"<key_id>": "<base64 32 bytes>", ...}}

Several KEKs can exist at once: the active one wraps new DEKs and older ones still unwrap,
so rotating means adding a key and re-wrapping DEKs, never re-encrypting data.
"""

from __future__ import annotations

import base64
import binascii
import json
import os
import secrets
import stat
from datetime import UTC, datetime
from pathlib import Path
from typing import Final

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from skyline_core.crypto.context import EncryptionContext
from skyline_core.crypto.errors import CryptoError, DecryptionError, KeyNotFoundError
from skyline_core.crypto.keyprovider import DataKey

_FORMAT: Final = "skyline-local-kek"
_KEY_BYTES: Final = 32
_NONCE_BYTES: Final = 12
_DEK_AAD_PREFIX: Final = b"skyline-dek-v1\x00"
_MAX_FILE_BYTES: Final = 64 * 1024


def _dek_aad(key_id: str, ctx: EncryptionContext) -> bytes:
    encoded_id = key_id.encode()
    return _DEK_AAD_PREFIX + len(encoded_id).to_bytes(2, "big") + encoded_id + ctx.aad()


class LocalKeyProvider:
    """Wraps DEKs with AES-256-GCM under a local KEK. Implements :class:`KeyProvider`."""

    def __init__(self, keys: dict[str, bytes], active_key_id: str) -> None:
        if active_key_id not in keys:
            msg = "active KEK is missing from the key file"
            raise CryptoError(msg)
        if any(len(k) != _KEY_BYTES for k in keys.values()):
            msg = "every KEK must be 32 bytes"
            raise CryptoError(msg)
        self._keys = dict(keys)
        self._active = active_key_id

    @property
    def name(self) -> str:
        return "local"

    @property
    def active_key_id(self) -> str:
        return self._active

    def __repr__(self) -> str:
        return f"LocalKeyProvider(active={self._active!r}, keys=***)"

    @classmethod
    def from_file(cls, path: Path) -> LocalKeyProvider:
        """Load a KEK file. On POSIX, refuse files readable by other users."""
        try:
            info = path.stat()
        except OSError as exc:
            msg = "KEK file cannot be read"
            raise CryptoError(msg) from exc
        if os.name == "posix" and info.st_mode & (stat.S_IRWXG | stat.S_IRWXO):
            msg = "KEK file permissions are too open (expected 0400 or 0600)"
            raise CryptoError(msg)
        if info.st_size > _MAX_FILE_BYTES:
            msg = "KEK file is larger than expected"
            raise CryptoError(msg)
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
            if document.get("format") != _FORMAT or document.get("version") != 1:
                raise ValueError
            keys = {
                str(key_id): base64.b64decode(value, validate=True)
                for key_id, value in document["keys"].items()
            }
            active = str(document["active"])
        except (ValueError, KeyError, TypeError, AttributeError, binascii.Error) as exc:
            msg = "KEK file is malformed"
            raise CryptoError(msg) from exc
        return cls(keys, active)

    async def generate_data_key(self, ctx: EncryptionContext) -> DataKey:
        dek = bytearray(secrets.token_bytes(_KEY_BYTES))
        nonce = secrets.token_bytes(_NONCE_BYTES)
        wrapped = nonce + AESGCM(self._keys[self._active]).encrypt(
            nonce, bytes(dek), _dek_aad(self._active, ctx)
        )
        return DataKey(plaintext=dek, wrapped=wrapped, key_id=self._active)

    async def unwrap(self, wrapped: bytes, key_id: str, ctx: EncryptionContext) -> bytearray:
        kek = self._keys.get(key_id)
        if kek is None:
            raise KeyNotFoundError
        if len(wrapped) <= _NONCE_BYTES:
            raise DecryptionError
        nonce, body = wrapped[:_NONCE_BYTES], wrapped[_NONCE_BYTES:]
        try:
            return bytearray(AESGCM(kek).decrypt(nonce, body, _dek_aad(key_id, ctx)))
        except InvalidTag as exc:
            raise DecryptionError from exc


def _new_key_id() -> str:
    return f"kek-{datetime.now(UTC):%Y%m%d}-{secrets.token_hex(4)}"


def create_kek_file(path: Path) -> str:
    """Create a new KEK file with one active key (mode 0400). Refuses to overwrite.

    Returns the new key ID (not secret).
    """
    key_id = _new_key_id()
    document = {
        "format": _FORMAT,
        "version": 1,
        "active": key_id,
        "keys": {key_id: base64.b64encode(secrets.token_bytes(_KEY_BYTES)).decode()},
    }
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_BINARY", 0)
    fd = os.open(path, flags, 0o400)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        json.dump(document, handle)
    return key_id
